/**
 * Tracks as editable text, plus the parser.
 *
 * A track is drawn as a grid of characters:
 *
 *   #    wall
 *   .    track
 *   F    the start and finish line
 *   1-9  checkpoint with that number
 *        (space) outside the track, never drawn
 *
 * Walls and the empty space outside the track are equally solid; the only
 * difference is that walls are drawn.
 *
 * Every car starts on the finish line, side by side, so the line needs at least
 * four cells and there are no separate starting cells. Cars are placed on it in
 * reading order: top to bottom, left to right.
 *
 * Draw the finish line and every checkpoint as an unbroken line across the full
 * width of the track. A car at speed 5 covers five cells in a single move, and
 * the only thing that stops it slipping past a line is that no route across the
 * track avoids it.
 *
 * Each track also carries:
 *
 *   finishDir  the direction the cars cross the line in, which is what makes a
 *              lap count one way round only
 *   route      the middle of the track, roughly, as a loop of cells in the
 *              driving order. The game draws arrows along it so nobody has to
 *              guess which way round to go. It does not have to be exact.
 *
 * The parser is deliberately strict: a broken track throws when it is loaded
 * rather than behaving oddly in the third corner.
 */

